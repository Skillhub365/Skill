-- 1. Monotonic ordering for session events
ALTER TABLE public.session_events
  ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX IF NOT EXISTS session_events_session_seq_idx
  ON public.session_events (session_id, seq);

-- 2. Lifecycle events: ordering + session/vm/source/progress detail
ALTER TABLE public.lifecycle_events
  ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS session_id uuid REFERENCES public.sessions(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS vm_id text,
  ADD COLUMN IF NOT EXISTS source text NOT NULL DEFAULT 'controller',
  ADD COLUMN IF NOT EXISTS progress integer,
  ADD COLUMN IF NOT EXISTS message text;

CREATE INDEX IF NOT EXISTS lifecycle_events_session_seq_idx
  ON public.lifecycle_events (session_id, seq);
CREATE INDEX IF NOT EXISTS lifecycle_events_vm_idx
  ON public.lifecycle_events (vm_id);

-- 3. Gateway connections: one live record per session + cleanup lookups
DELETE FROM public.gateway_connections a
  USING public.gateway_connections b
  WHERE a.session_id = b.session_id AND a.ctid < b.ctid;

CREATE UNIQUE INDEX IF NOT EXISTS gateway_connections_session_key
  ON public.gateway_connections (session_id);
CREATE INDEX IF NOT EXISTS gateway_connections_status_idx
  ON public.gateway_connections (status) WHERE cleaned_up_at IS NULL;
CREATE INDEX IF NOT EXISTS gateway_connections_expiry_idx
  ON public.gateway_connections (token_expires_at) WHERE cleaned_up_at IS NULL;

-- 4. Durable, lease-coordinated cleanup/reaper runs
CREATE TABLE IF NOT EXISTS public.cleanup_runs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  job text NOT NULL,
  worker_id text NOT NULL,
  status text NOT NULL DEFAULT 'running',
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  lease_until timestamptz NOT NULL DEFAULT now() + interval '2 minutes',
  reclaimed integer NOT NULL DEFAULT 0,
  failures integer NOT NULL DEFAULT 0,
  detail text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.cleanup_runs TO authenticated;
GRANT ALL ON public.cleanup_runs TO service_role;

ALTER TABLE public.cleanup_runs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins can read cleanup runs"
  ON public.cleanup_runs FOR SELECT TO authenticated
  USING (app_private.is_admin(auth.uid()));

-- Only one live lease per job across every app instance.
CREATE UNIQUE INDEX IF NOT EXISTS cleanup_runs_active_job_key
  ON public.cleanup_runs (job) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS cleanup_runs_job_started_idx
  ON public.cleanup_runs (job, started_at DESC);